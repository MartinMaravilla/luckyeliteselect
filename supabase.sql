create extension if not exists pgcrypto;

create table if not exists public.raffles (
  id uuid primary key,
  name text not null,
  tagline text,
  prize text not null,
  price integer not null default 250,
  total_tickets integer not null default 1000,
  draw_at timestamptz not null,
  bonus_threshold integer not null default 300,
  winner_number text
);

create table if not exists public.buyers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  whatsapp text not null,
  city text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.tickets (
  id bigint generated by default as identity primary key,
  raffle_id uuid not null references public.raffles(id) on delete cascade,
  number text not null,
  status text not null default 'available' check(status in ('available','reserved','paid','winner')),
  buyer_id uuid references public.buyers(id),
  reserved_until timestamptz,
  updated_at timestamptz not null default now(),
  unique(raffle_id,number)
);

